    def _extract_identifier_from_hcl(self, terragrunt_content: str) -> str:
        """
        Extract identifier or service name from terragrunt HCL content.
        Looks for 'identifier' or 'service' field in the HCL content.

        Args:
            terragrunt_content: Terragrunt HCL file content

        Returns:
            Identifier/service name from HCL content

        Raises:
            GitHubValidationError: If identifier/service not found in HCL
        """
        # Pattern to match identifier = "value" or service = "value"
        identifier_pattern = r'(?:identifier|service)\s*=\s*["\']([^"\']+)["\']'

        match = re.search(identifier_pattern, terragrunt_content)

        if not match:
            raise GitHubValidationError([
                "Could not find 'identifier' or 'service' field in terragrunt HCL content. "
                "Please ensure the HCL contains either 'identifier = \"value\"' or 'service = \"value\"'"
            ])

        return match.group(1).strip()

    def _extract_value_from_hcl(self, terragrunt_content: str, field_name: str, nested: bool = False) -> str:
        """
        Extract a field value from terragrunt HCL content.

        Args:
            terragrunt_content: Terragrunt HCL file content
            field_name: Field name to extract (e.g., 'name', 'type', 'query')
            nested: If True, search within nested blocks (e.g., monitor_thresholds.critical)

        Returns:
            Field value from HCL content

        Raises:
            ValueError: If field not found in HCL
        """
        if nested:
            # For nested values like critical in monitor_thresholds
            pattern = rf'{field_name}\s*=\s*([^\s,\n}}]+)'
        else:
            # For string values: field = "value" or field = """value"""
            pattern = rf'{field_name}\s*=\s*(?:"""([^"]*?)"""|"([^"]+)"|(\S+))'

        match = re.search(pattern, terragrunt_content, re.DOTALL)

        if not match:
            return ""

        # Return the first non-None group
        for group in match.groups():
            if group is not None:
                return group.strip()

        return ""

