    def _check_and_add_database(self, content: str, database_name: str) -> tuple:
        """
        Check if database exists and add to appropriate array (mysql_databases or psql_databases).

        Logic:
        1. Check if mysql_databases array exists → search/append there
        2. Else check if psql_databases array exists → search/append there
        3. If neither exists → raise error

        Args:
            content: Full HCL file content
            database_name: Name of the database to add

        Returns:
            tuple: (modified_content, db_type) where db_type is 'mysql' or 'psql'

        Raises:
            ValueError: If database already exists or no database array found
        """
        # Check for mysql_databases array first
        mysql_pattern = r'mysql_databases\s*=\s*\['
        mysql_match = re.search(mysql_pattern, content)

        if mysql_match:
            # It's a MySQL server - check if database already exists
            if self._check_database_exists_in_array(content, database_name, 'mysql'):
                raise ValueError(f"Database '{database_name}' already exists in mysql_databases array")

            # Add database to mysql_databases array
            modified_content = self._add_database_to_array(content, database_name, 'mysql')
            return modified_content, 'mysql'

        # Check for psql_databases array
        psql_pattern = r'psql_databases\s*=\s*\['
        psql_match = re.search(psql_pattern, content)

        if psql_match:
            # It's a PostgreSQL server - check if database already exists
            if self._check_database_exists_in_array(content, database_name, 'psql'):
                raise ValueError(f"Database '{database_name}' already exists in psql_databases array")

            # Add database to psql_databases array
            modified_content = self._add_database_to_array(content, database_name, 'psql')
            return modified_content, 'psql'

        # Neither array found
        raise ValueError("No database array found in file (neither mysql_databases nor psql_databases)")

    def _check_database_exists_in_array(self, content: str, database_name: str, db_type: str) -> bool:
        """
        Check if a database name already exists in the specified database array.

        Args:
            content: Full HCL file content
            database_name: Database name to check
            db_type: 'mysql' or 'psql'

        Returns:
            True if database exists, False otherwise
        """
        array_name = 'mysql_databases' if db_type == 'mysql' else 'psql_databases'

        # Find the array and extract its contents
        pattern = rf'{array_name}\s*=\s*\[(.*?)\]'
        match = re.search(pattern, content, re.DOTALL)

        if not match:
            return False

        array_content = match.group(1)
        # Check if database name exists as a quoted string in the array
        db_pattern = rf'"\s*{re.escape(database_name)}\s*"'
        return bool(re.search(db_pattern, array_content))

    def _add_database_to_array(self, content: str, database_name: str, db_type: str) -> str:
        """
        Add a database name to the specified database array.

        Args:
            content: Full HCL file content
            database_name: Database name to add
            db_type: 'mysql' or 'psql'

        Returns:
            Modified HCL content with database added to array
        """
        array_name = 'mysql_databases' if db_type == 'mysql' else 'psql_databases'

        # Find the array
        pattern = rf'({array_name}\s*=\s*\[)'
        match = re.search(pattern, content)
        if not match:
            raise ValueError(f"{array_name} array not found in content")

        # Find the closing bracket of the array
        array_start = match.end()
        bracket_depth = 1
        i = array_start
        in_string = False
        escape_next = False

        while i < len(content) and bracket_depth > 0:
            char = content[i]

            if escape_next:
                escape_next = False
                i += 1
                continue

            if char == '\\':
                escape_next = True
                i += 1
                continue

            if char == '"' and not in_string:
                in_string = True
                i += 1
                continue

            if char == '"' and in_string:
                in_string = False
                i += 1
                continue

            if not in_string:
                if char == '[':
                    bracket_depth += 1
                elif char == ']':
                    bracket_depth -= 1

            i += 1

        array_end = i - 1  # Position of closing ]

        # Check if array is empty or has content
        array_content = content[array_start:array_end].strip()

        if array_content:
            # Has existing databases - add comma and new database on new line
            content_before_bracket = content[:array_end].rstrip()

            # Detect indentation from existing array content
            # Find the last line before closing bracket to get indentation
            lines_before = content[:array_end].split('\n')
            last_content_line = ''
            for line in reversed(lines_before):
                stripped = line.strip()
                if stripped and stripped != '[':
                    last_content_line = line
                    break

            # Extract indentation (spaces/tabs before content)
            indent = ''
            for char in last_content_line:
                if char in ' \t':
                    indent += char
                else:
                    break

            # If no indentation found, use 4 spaces as default
            if not indent:
                indent = '    '

            # Check if already ends with comma to avoid double comma
            # Add newline before closing bracket to keep it on its own line
            if content_before_bracket.endswith(','):
                insert_text = f'\n{indent}"{database_name}"\n'
            else:
                insert_text = f',\n{indent}"{database_name}"\n'
            return content_before_bracket + insert_text + content[array_end:]
        else:
            # Empty array - add database with newline before closing bracket
            insert_text = f'\n    "{database_name}"\n'
            return content[:array_start] + insert_text + content[array_end:]

    def _ensure_create_alarms(self, hcl_content: str) -> str:
        """
        Ensure create_alarms is present and set to false in the inputs block.

        Args:
            hcl_content: Full HCL file content

        Returns:
            Modified HCL content with create_alarms = false
        """
        # Check if create_alarms exists
        create_alarms_pattern = r'create_alarms\s*=\s*(true|false)'
        match = re.search(create_alarms_pattern, hcl_content)

        if match:
            # Exists - check if it's true and update to false
            if match.group(1) == 'true':
                logger.info("Found create_alarms = true, updating to false")
                hcl_content = re.sub(
                    r'create_alarms\s*=\s*true',
                    'create_alarms = false',
                    hcl_content
                )
        else:
            # Doesn't exist - add it before monitors list
            logger.info("create_alarms not found, adding it")

            # Find the monitors = [ line and add create_alarms before it
            monitors_line_pattern = r'(\s*)(monitors\s*=\s*\[)'
            match = re.search(monitors_line_pattern, hcl_content)

            if match:
                indent = match.group(1)
                # Insert create_alarms before monitors
                hcl_content = re.sub(
                    monitors_line_pattern,
                    f'{indent}create_alarms = false\n\n{indent}monitors = [',
                    hcl_content,
                    count=1
                )
            else:
                # Fallback: add at end of inputs block if monitors not found
                # Find closing brace of inputs
                inputs_pattern = r'(inputs\s*=\s*\{)(.*?)(\n\})'
                match = re.search(inputs_pattern, hcl_content, re.DOTALL)
                if match:
                    inputs_start = match.group(1)
                    inputs_content = match.group(2)
                    inputs_end = match.group(3)
                    hcl_content = hcl_content.replace(
                        match.group(0),
                        f"{inputs_start}{inputs_content}\n\n  create_alarms = false{inputs_end}"
                    )

        return hcl_content

    def _ensure_datadog_api_keys(self, hcl_content: str) -> str:
        """
        Ensure encrypted_datadog_api_key and encrypted_datadog_app_key
        are present in the inputs block. If missing, add them.

        Args:
            hcl_content: Full HCL file content

        Returns:
            Modified HCL content with Datadog API keys if they were missing
        """
        # Check if both keys exist
        has_api_key = bool(re.search(r'encrypted_datadog_api_key\s*=', hcl_content))
        has_app_key = bool(re.search(r'encrypted_datadog_app_key\s*=', hcl_content))

        if has_api_key and has_app_key:
            logger.info("Both encrypted_datadog_api_key and encrypted_datadog_app_key already present")
            return hcl_content  # Both present, nothing to do

        logger.info(f"Missing Datadog keys - api_key: {not has_api_key}, app_key: {not has_app_key}")

        # Find the monitors = [ line and add keys before it
        # Look for optional comment: // Data dog monitor list.
        # Use [ \t]* to capture only horizontal whitespace (not newlines)
        monitors_line_pattern = r'([ \t]*)((?://\s*Data\s*dog\s*monitor\s*list\.\s*\n\s*)?monitors\s*=\s*\[)'
        match = re.search(monitors_line_pattern, hcl_content, re.IGNORECASE)

        if match:
            indent = match.group(1)
            keys_to_add = []

            if not has_api_key:
                keys_to_add.append(f'{indent}encrypted_datadog_api_key = include.env.locals.encrypted_datadog_api_key')
            if not has_app_key:
                keys_to_add.append(f'{indent}encrypted_datadog_app_key = include.env.locals.encrypted_datadog_app_key')

            if keys_to_add:
                # Add "// DATADOG" comment and keys before monitors - single newline between each
                keys_block = f"{indent}// DATADOG\n" + "\n".join(keys_to_add) + "\n\n"
                hcl_content = re.sub(
                    monitors_line_pattern,
                    f'{keys_block}{match.group(2)}',
                    hcl_content,
                    count=1
                )
                logger.info(f"Added {len(keys_to_add)} Datadog key(s) before monitors section")
        else:
            logger.warning("Could not find monitors section to add Datadog keys")

        return hcl_content

    def _add_atlantis_project_entry(
        self,
        atlantis_content: str,
        file_path: str,
        product_name: str,
        env: str,
        identifier: str,
        resource_type: str,
        tenant: str = "",
        geo_loc: str = ""
    ) -> str:
        """
        Add a new project entry to atlantis.yaml at the beginning of projects list.

        Args:
            atlantis_content: Current atlantis.yaml content
            file_path: Full terragrunt file path (e.g., "environment/core-stage-01/ap-south-1/buckets/my-bucket/terragrunt.hcl")
            product_name: Product name (e.g., "core")
            env: Environment (e.g., "stage", "dev", "prod")
            identifier: Resource identifier
            resource_type: Resource type ("s3" or "sqs")
            tenant: Tenant identifier (for tenant-specific folder names)
            geo_loc: Geographic location code for core-prod atlantis naming (e.g., 'mumbai', 'london')

        Returns:
            Modified atlantis.yaml content with new project entry
        """
        # Derive dir from file_path by removing "/terragrunt.hcl"
        dir_path = file_path.replace("/terragrunt.hcl", "")

        # Sanitize values for name construction
        product_sanitized = re.sub(r'[\s_-]+', '-', product_name.strip()).strip('-').lower()
        env_sanitized = self._get_folder_env(env, tenant)
        identifier_sanitized = re.sub(r'[\s_-]+', '-', identifier.strip()).strip('-').lower()

        # Build name and workflow based on resource type
        # Include normalized geo_loc for core-prod only
        if resource_type == "s3":
            if product_sanitized == "core" and env_sanitized == "prod" and geo_loc:
                geo_loc_normalized = self._normalize_geo_loc_for_atlantis(geo_loc)
                name = f"{product_sanitized}-{env_sanitized}-{geo_loc_normalized}-{identifier_sanitized}-bucket"
            else:
                name = f"{product_sanitized}-{env_sanitized}-{identifier_sanitized}-bucket"
            workflow = "terragrunt"
        elif resource_type == "sqs":
            if product_sanitized == "core" and env_sanitized == "prod" and geo_loc:
                geo_loc_normalized = self._normalize_geo_loc_for_atlantis(geo_loc)
                name = f"{product_sanitized}-{env_sanitized}-{geo_loc_normalized}-{identifier_sanitized}-queue"
            else:
                name = f"{product_sanitized}-{env_sanitized}-{identifier_sanitized}-queue"
            workflow = "terragrunt"
        else:
            raise ValueError(f"Unsupported resource type for atlantis entry: {resource_type}")

        # Get the branch for Atlantis entry (main for all prod, stage for Vance/Aspora dev/staging)
        atlantis_branch = self._get_atlantis_branch(env, tenant)

        # Build the new project entry with exact formatting (2-space indents)
        new_entry = f"  - name: {name}\n"
        new_entry += f"    dir: {dir_path}\n"
        new_entry += f"    workflow: {workflow}\n"
        new_entry += f"    branch: /{atlantis_branch}/\n"

        # Find the projects: section and insert at the beginning
        # Preserve blank line after "projects:" if it exists
        if 'projects:\n\n' in atlantis_content:
            # Has blank line - preserve it
            atlantis_content = atlantis_content.replace(
                'projects:\n\n',
                f'projects:\n\n{new_entry}',
                1  # Only replace first occurrence
            )
            logger.info(f"Added atlantis project entry: {name}")
        elif 'projects:\n' in atlantis_content:
            # No blank line - add entry directly
            atlantis_content = atlantis_content.replace(
                'projects:\n',
                f'projects:\n{new_entry}',
                1  # Only replace first occurrence
            )
            logger.info(f"Added atlantis project entry: {name}")
        else:
            logger.warning("Could not find projects: section in atlantis.yaml")

        return atlantis_content

