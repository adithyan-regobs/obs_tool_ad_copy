    @staticmethod
    def _parse_bool(value, default: bool = False) -> bool:
        """
        Parse boolean from various formats (bool, string, None).

        Handles the case where frontend sends "false" as string instead of boolean,
        which would be truthy in Python (bool("false") == True).

        Args:
            value: The value to parse (bool, str, or None)
            default: Default value if value is None

        Returns:
            Parsed boolean value
        """
        if value is None:
            return default
        if isinstance(value, bool):
            return value
        if isinstance(value, str):
            return value.lower() in ('true', '1', 'yes')
        return bool(value)

    @staticmethod
    def _normalize_region_for_path(region: str) -> str:
        """
        Normalize region name for folder paths.
        Strips cloud provider prefix (aws-, azure-, gcp-) from region names.

        Args:
            region: Region name (e.g., 'aws-ap-south-1', 'ap-south-1')

        Returns:
            Normalized region name without cloud provider prefix

        Examples:
            'aws-ap-south-1' -> 'ap-south-1'
            'azure-eastus' -> 'eastus'
            'gcp-us-central1' -> 'us-central1'
            'ap-south-1' -> 'ap-south-1' (unchanged)
        """
        region_lower = region.strip().lower()

        # Strip cloud provider prefixes
        for prefix in ['aws-', 'azure-', 'gcp-']:
            if region_lower.startswith(prefix):
                return region_lower[len(prefix):]

        return region_lower

    def _extract_monitor_blocks(self, content: str) -> list:
        """
        Extract monitor blocks from HCL content while respecting quoted strings.

        This properly handles braces inside quoted strings (like Datadog queries)
        which contain {...} patterns that should not be treated as HCL blocks.
        Preserves leading indentation for each block.     
        Args:
            content: String content containing monitor blocks

        Returns:
            List of monitor block strings with preserved indentation
        """
        blocks = []
        i = 0

        while i < len(content):
            # Skip commas and newlines, but track where indentation starts
            while i < len(content) and content[i] in ',\n\r':
                i += 1

            if i >= len(content):
                break

            # Capture leading whitespace (indentation) for this line
            indent_start = i
            while i < len(content) and content[i] in ' \t':
                i += 1

            if i >= len(content):
                break

            # Look for opening brace
            if content[i] == '{':
                brace_depth = 0
                in_string = False
                escape_next = False

                # Scan through content tracking braces and strings
                while i < len(content):
                    char = content[i]

                    if escape_next:
                        escape_next = False
                        i += 1
                        continue

                    if char == '\\':
                        escape_next = True
                        i += 1
                        continue

                    if char == '"' and not in_string:
                        in_string = True
                        i += 1
                        continue

                    if char == '"' and in_string:
                        in_string = False
                        i += 1
                        continue

                    # Only count braces outside of strings
                    if not in_string:
                        if char == '{':
                            brace_depth += 1
                        elif char == '}':
                            brace_depth -= 1
                            if brace_depth == 0:
                                # Found matching closing brace - extract from indent_start to preserve indentation
                                block = content[indent_start:i+1]
                                blocks.append(block)
                                i += 1
                                break

                    i += 1
            else:
                i += 1

        return blocks

    def _extract_monitors_list_content(self, hcl_content: str) -> str:
        """
        Extract the content inside monitors = [...] properly counting brackets.

        Args:
            hcl_content: Full HCL file content

        Returns:
            Content inside the monitors array, or empty string if not found
        """
        # Find "monitors = ["
        monitors_start = hcl_content.find('monitors')
        if monitors_start == -1:
            return ""

        # Find the opening bracket
        bracket_start = hcl_content.find('[', monitors_start)
        if bracket_start == -1:
            return ""

        # Count brackets to find matching closing bracket
        bracket_depth = 0
        in_string = False
        escape_next = False
        i = bracket_start

        while i < len(hcl_content):
            char = hcl_content[i]

            if escape_next:
                escape_next = False
                i += 1
                continue

            if char == '\\':
                escape_next = True
                i += 1
                continue

            if char == '"' and not in_string:
                in_string = True
                i += 1
                continue

            if char == '"' and in_string:
                in_string = False
                i += 1
                continue

            # Only count brackets outside of strings
            if not in_string:
                if char == '[':
                    bracket_depth += 1
                elif char == ']':
                    bracket_depth -= 1
                    if bracket_depth == 0:
                        # Found matching closing bracket
                        return hcl_content[bracket_start + 1:i].strip()

            i += 1

        return ""

    def _check_route_exists_in_hcl_content(
        self,
        content: str,
        api_name: str,
        method: str,
        route: str
    ) -> bool:
        """
        Check if a route already exists in the HCL file's method array for a specific API.

        Args:
            content: Full HCL file content
            api_name: API service name (e.g., "partner-dashboard-api")
            method: HTTP method (e.g., "GET", "POST")
            route: Kong route pattern (e.g., "~/api/v1/users$")

        Returns:
            True if route exists in the specified API's method array, False otherwise

        Example:
            If "user-api" has GET = ["~/api/v1/users$"], then:
            - check("user-api", "GET", "~/api/v1/users$") → True (duplicate)
            - check("user-api", "POST", "~/api/v1/users$") → False (different method, allowed)
            - check("product-api", "GET", "~/api/v1/users$") → False (different API, allowed)
        """
        try:
            # Step 1: Find the API block
            api_pattern = f'"{api_name}"'
            api_start = content.find(api_pattern)
            if api_start == -1:
                # API doesn't exist in content - route cannot be duplicate
                return False

            # Step 2: Find routes = { within the API block
            routes_search_start = content.find('{', api_start)
            routes_pattern = 'routes'
            routes_start = content.find(routes_pattern, routes_search_start)

            if routes_start == -1:
                # Routes section doesn't exist - route cannot be duplicate
                return False

            # Find the opening { for routes
            routes_brace_start = content.find('{', routes_start)

            # Step 3: Find the method array within routes
            method_pattern = f'"{method}"'
            method_start = content.find(method_pattern, routes_brace_start)

            if method_start == -1:
                # Method doesn't exist - route cannot be duplicate
                return False

            # Step 4: Find the array opening [ for this method
            array_start = content.find('[', method_start)
            if array_start == -1:
                return False

            # Step 5: Find the matching closing ] for this array
            bracket_depth = 0
            i = array_start
            array_end = -1
            in_string = False
            escape_next = False

            while i < len(content):
                char = content[i]

                # Handle escape sequences
                if escape_next:
                    escape_next = False
                    i += 1
                    continue

                if char == '\\':
                    escape_next = True
                    i += 1
                    continue

                # Handle string literals
                if char == '"' and not in_string:
                    in_string = True
                    i += 1
                    continue

                if char == '"' and in_string:
                    in_string = False
                    i += 1
                    continue

                # Only count brackets outside of strings
                if not in_string:
                    if char == '[':
                        bracket_depth += 1
                    elif char == ']':
                        bracket_depth -= 1
                        if bracket_depth == 0:
                            array_end = i
                            break

                i += 1

            if array_end == -1:
                return False

            # Step 6: Extract array content and check if route exists
            array_content = content[array_start + 1:array_end].strip()
            route_pattern = f'"{route}"'

            # Route exists if the exact pattern is found in the array content
            return route_pattern in array_content

        except Exception as e:
            # If parsing fails, log and return False (assume no duplicate)
            logger.warning(f"Failed to parse HCL content for duplicate check: {str(e)}")
            return False

    def _add_route_to_method_array(
        self,
        content: str,
        api_name: str,
        method: str,
        route: str
    ) -> str:
        """
        Add a route to the bottom of a method's array in gateway kong_configs.

        Args:
            content: Full HCL file content
            api_name: API service name (e.g., "partner-dashboard-api")
            method: HTTP method (e.g., "GET", "POST")
            route: Kong route pattern (e.g., "~/api/v1/users$")

        Returns:
            Modified content with route added to the method array

        Example:
            Before: "GET" = ["~/api/v1/users$"]
            After:  "GET" = ["~/api/v1/users$", "~/api/v1/products$"]
        """
        # Step 1: Find the API block
        api_pattern = f'"{api_name}"'
        api_start = content.find(api_pattern)
        if api_start == -1:
            raise ValueError(f"API '{api_name}' not found in content")

        # Step 2: Find routes = { within the API block
        # Start searching after the API name
        routes_search_start = content.find('{', api_start)
        routes_pattern = 'routes'
        routes_start = content.find(routes_pattern, routes_search_start)

        if routes_start == -1:
            raise ValueError(f"routes section not found for API '{api_name}'")

        # Find the opening { for routes
        routes_brace_start = content.find('{', routes_start)

        # Step 3: Find the method array within routes
        method_pattern = f'"{method}"'
        method_start = content.find(method_pattern, routes_brace_start)

        # If method doesn't exist, we need to add it
        # For now, let's handle the case where method exists
        if method_start == -1:
            # Method doesn't exist - need to create it
            # Find the closing } of routes map and add before it
            raise ValueError(f"Method '{method}' not found in routes for API '{api_name}'. Creating new methods is not yet supported.")

        # Step 4: Find the array opening [ for this method
        array_start = content.find('[', method_start)
        if array_start == -1:
            raise ValueError(f"Array not found for method '{method}'")

        # Step 5: Find the matching closing ] for this array
        # Need to handle nested brackets
        bracket_depth = 0
        i = array_start
        array_end = -1
        in_string = False
        escape_next = False

        while i < len(content):
            char = content[i]

            # Handle escape sequences
            if escape_next:
                escape_next = False
                i += 1
                continue

            if char == '\\':
                escape_next = True
                i += 1
                continue

            # Handle string literals
            if char == '"' and not in_string:
                in_string = True
                i += 1
                continue

            if char == '"' and in_string:
                in_string = False
                i += 1
                continue

            # Only count brackets outside of strings
            if not in_string:
                if char == '[':
                    bracket_depth += 1
                elif char == ']':
                    bracket_depth -= 1
                    if bracket_depth == 0:
                        array_end = i
                        break

            i += 1

        if array_end == -1:
            raise ValueError(f"Could not find closing ] for method '{method}' array")

        # Step 6: Extract current array content
        array_content = content[array_start + 1:array_end].strip()

        # Step 7: Check if route already exists (idempotent check)
        route_pattern = f'"{route}"'
        if route_pattern in array_content:
            logger.info(f"Route '{route}' already exists in {api_name}.{method} - no changes needed")
            print(f"\n✅ Route already exists - no changes needed\n")
            return content

        # Step 8: Add the new route at the end
        # Determine if we need a comma (if array is not empty)
        needs_comma = len(array_content.strip()) > 0

        # Insert the new route before the closing ]
        if needs_comma:
            new_route_entry = f', "{route}"'
        else:
            new_route_entry = f'"{route}"'

        # Build the modified content
        modified_content = (
            content[:array_end] +
            new_route_entry +
            content[array_end:]
        )

        logger.info(f"Successfully added route '{route}' to {api_name}.{method}")
        print(f"\n✅ Added route to {method} array\n")

        return modified_content

