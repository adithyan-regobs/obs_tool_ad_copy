    def _fix_source_path(self, terragrunt_content: str, resource_type: str) -> str:
        """
        Fix the source path in terragrunt HCL to use the correct number of parent directory references.

        Folder structures (both require 8 levels to reach root):
        - AWS: tenant/{tenant}/{env}/{version}/{region}/aws/{resource_type}/{identifier}/terragrunt.hcl (8 levels)
        - Datadog: tenant/{tenant}/{env}/{version}/datadog/monitor/{resource_type_ref}/{identifier}/terragrunt.hcl (8 levels)

        Args:
            terragrunt_content: Original HCL content
            resource_type: Resource type (e.g., s3-bucket, sqs, datadog/monitor)

        Returns:
            HCL content with corrected source path
        """
        # Pattern to match source = "path/to/layers/..."
        # Captures the layers path after any number of ../
        source_pattern = r'(source\s*=\s*["\'])(?:\.\.\/)*(\/?layers\/[^"\']+)(["\'])'

        # Determine the correct resource folder name in layers
        # Map resource_type to the actual folder name in layers/aws/ or layers/datadog/
        resource_mapping = {
            's3': 's3_bucket',
            's3-bucket': 's3_bucket',
            's3_bucket': 's3_bucket',
            'sqs': 'queue',
            'queue': 'queue',
            'datadog-monitor': 'monitor',
            'datadog/monitor': 'monitor',
        }

        # Get the actual layer folder name
        layer_folder = resource_mapping.get(resource_type.lower().replace('-', '_'), resource_type)

        # Determine the provider (aws or datadog)
        provider = 'datadog' if 'datadog' in resource_type.lower() else 'aws'

        # Both AWS and Datadog need 8 levels to reach root from terragrunt.hcl
        # AWS: tenant/{tenant}/{env}/{version}/{region}/aws/{resource}/{identifier}/terragrunt.hcl (8 levels)
        # Datadog: tenant/{tenant}/{env}/{version}/datadog/monitor/{resource_type_ref}/{identifier}/terragrunt.hcl (8 levels)
        correct_path = f'../../../../../../../../layers/{provider}/{layer_folder}'

        # Replace with the correct path
        fixed_content = re.sub(
            source_pattern,
            rf'\g<1>{correct_path}\g<3>',
            terragrunt_content
        )

        if fixed_content != terragrunt_content:
            logger.info(f"Fixed source path in terragrunt HCL to: {correct_path}")

        return fixed_content

    async def _run_terragrunt_plan(self, directory: str) -> Dict[str, Any]:
        """
        Run terragrunt plan in the specified directory to preview changes.

        Args:
            directory: Directory containing terragrunt.hcl file

        Returns:
            Dict with success status and plan output

        Raises:
            Exception: If terragrunt plan fails
        """
        try:
            logger.info(f"Running terragrunt plan in {directory}")

            # Build environment with Datadog credentials
            parsed_url = urlparse(settings.datadog_base_url)
            datadog_api_url = f"{parsed_url.scheme}://{parsed_url.netloc}/"

            env_vars = {
                **os.environ,
                "TF_INPUT": "false",
                "DATADOG_API_KEY": settings.datadog_api_key,
                "DATADOG_APP_KEY": settings.datadog_app_key,
                "DATADOG_API_URL": datadog_api_url,
            }

            process = await asyncio.create_subprocess_exec(
                "terragrunt", "plan",
                cwd=directory,
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.PIPE,
                env=env_vars
            )

            try:
                stdout, stderr = await asyncio.wait_for(
                    process.communicate(),
                    timeout=300  # 5 minute timeout
                )
            except asyncio.TimeoutError:
                process.kill()
                await process.wait()
                logger.error("Terragrunt plan timed out after 5 minutes")
                raise Exception("Terragrunt plan timed out after 5 minutes")

            stdout_str = stdout.decode() if stdout else ""
            stderr_str = stderr.decode() if stderr else ""

            if process.returncode != 0:
                logger.error(f"Terragrunt plan failed: {stderr_str}")
                raise Exception(f"Terragrunt plan failed with exit code {process.returncode}: {stderr_str}")

            logger.info(f"Terragrunt plan successful")

            return {
                "success": True,
                "output": stdout_str,
                "message": "Terragrunt plan completed successfully"
            }

        except FileNotFoundError:
            logger.error("Terragrunt command not found")
            raise Exception("Terragrunt command not found. Please ensure terragrunt is installed and in PATH")

