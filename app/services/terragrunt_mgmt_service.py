    def _check_mysql_user_exists(self, content: str, username: str) -> bool:
        """
        Check if a MySQL user exists in mysql_users array.

        Args:
            content: Full HCL file content
            username: Database username to check

        Returns:
            True if user exists, False otherwise
        """
        pattern = f'name\\s*=\\s*"{username}"'
        return bool(re.search(pattern, content))

    def _add_or_merge_mysql_user(
        self,
        existing_content: str,
        username: str,
        password: str,
        grants: List[Dict],
        update_password: bool = False,
        replace_grants: bool = True
    ) -> str:
        """
        Add new user or merge grants into existing user in mysql_users array.

        Args:
            existing_content: Current HCL file content
            username: Database username
            password: KMS encrypted password
            grants: List of grants with structure:
                    [{database: str, tables: [{table: str, privileges: [str]}]}]
                    Note: table="all" maps to HCL table="*"
            update_password: If True, update password for existing user
            replace_grants: If True (default), new grants replace existing grants entirely.
                           If False, merge/union privileges with existing grants.

        Returns:
            Modified HCL content
        """
        # Flatten grants to HCL format
        hcl_grants = []
        for grant in grants:
            database = grant["database"]
            for table_grant in grant.get("tables", []):
                table = table_grant["table"]
                # Map "all" → "*" for HCL
                hcl_table = "*" if table == "all" else table
                privileges = table_grant["privileges"]
                hcl_grants.append({
                    "database": database,
                    "table": hcl_table,
                    "privileges": privileges
                })

        if self._check_mysql_user_exists(existing_content, username):
            # User exists → merge or replace grants based on replace_grants flag
            if replace_grants:
                logger.info(f"User '{username}' exists - replacing grants")
                print(f"\n⚠️  User '{username}' already exists - replacing grants\n")
            else:
                logger.info(f"User '{username}' exists - merging grants")
                print(f"\n⚠️  User '{username}' already exists - merging grants\n")
            return self._merge_mysql_user_grants(
                existing_content, username, hcl_grants,
                password=password, update_password=update_password,
                replace_grants=replace_grants
            )
        else:
            # User doesn't exist → add new user
            logger.info(f"User '{username}' does not exist - adding new user")
            print(f"\n✅ Adding new user '{username}'\n")
            return self._add_mysql_user(existing_content, username, password, hcl_grants)

    def _add_mysql_user(
        self,
        content: str,
        username: str,
        password: str,
        grants: List[Dict]
    ) -> str:
        """
        Add new user entry to mysql_users array.

        Args:
            content: Full HCL file content
            username: Database username
            password: KMS encrypted password
            grants: List of flattened grants [{database, table, privileges}]

        Returns:
            Modified HCL content with new user added
        """
        user_hcl = self._format_mysql_user_hcl(username, password, grants)

        # Find mysql_users = [ and its closing ]
        pattern = r'(mysql_users\s*=\s*\[)'
        match = re.search(pattern, content)
        if not match:
            raise ValueError("mysql_users array not found in content")

        # Find the closing bracket of mysql_users array
        array_start = match.end()
        bracket_depth = 1
        i = array_start
        in_string = False
        escape_next = False

        while i < len(content) and bracket_depth > 0:
            char = content[i]

            # Handle escape sequences
            if escape_next:
                escape_next = False
                i += 1
                continue

            if char == '\\':
                escape_next = True
                i += 1
                continue

            # Handle string literals
            if char == '"' and not in_string:
                in_string = True
                i += 1
                continue

            if char == '"' and in_string:
                in_string = False
                i += 1
                continue

            # Only count brackets outside of strings
            if not in_string:
                if char == '[':
                    bracket_depth += 1
                elif char == ']':
                    bracket_depth -= 1

            i += 1

        array_end = i - 1  # Position of closing ]

        # Check if array is empty or has content
        array_content = content[array_start:array_end].strip()
        if array_content:
            # Has existing users - strip trailing whitespace before ]
            content_before_bracket = content[:array_end].rstrip()
            # Check if already ends with comma to avoid double comma
            if content_before_bracket.endswith(','):
                insert_text = f"\n{user_hcl}\n  "
            else:
                insert_text = f",\n{user_hcl}\n  "
            return content_before_bracket + insert_text + content[array_end:]
        else:
            # Empty array - just add user
            insert_text = f"\n{user_hcl}\n  "
            return content[:array_end] + insert_text + content[array_end:]

    def _merge_mysql_user_grants(
        self,
        content: str,
        username: str,
        new_grants: List[Dict],
        password: str = None,
        update_password: bool = False,
        replace_grants: bool = True
    ) -> str:
        """
        Merge or replace grants in existing user's grants array.

        Args:
            content: Full HCL file content
            username: Database username
            new_grants: List of flattened grants [{database, table, privileges}]
            password: Password to set (only used if update_password=True)
            update_password: If True, also update the user's password
            replace_grants: If True (default), new grants replace existing grants entirely.
                           If False, merge/union privileges with existing grants.

        Returns:
            Modified HCL content with updated grants

        Logic:
            When replace_grants=True:
                - New grants completely replace existing grants
            When replace_grants=False:
                - Same (database, table) → union privileges
                - New (database, table) → add grant entry
        """
        # Find the user block by name
        user_pattern = f'name\\s*=\\s*"{username}"'
        user_match = re.search(user_pattern, content)
        if not user_match:
            raise ValueError(f"User '{username}' not found in content")

        # Find the grants array for this user
        # Search for "grants = [" after the user name
        grants_search_start = user_match.end()
        grants_pattern = r'grants\s*=\s*\['
        grants_match = re.search(grants_pattern, content[grants_search_start:])
        if not grants_match:
            raise ValueError(f"grants array not found for user '{username}'")

        grants_array_start = grants_search_start + grants_match.end()

        # Find the closing ] of grants array
        bracket_depth = 1
        i = grants_array_start
        in_string = False
        escape_next = False

        while i < len(content) and bracket_depth > 0:
            char = content[i]

            if escape_next:
                escape_next = False
                i += 1
                continue

            if char == '\\':
                escape_next = True
                i += 1
                continue

            if char == '"' and not in_string:
                in_string = True
                i += 1
                continue

            if char == '"' and in_string:
                in_string = False
                i += 1
                continue

            if not in_string:
                if char == '[':
                    bracket_depth += 1
                elif char == ']':
                    bracket_depth -= 1

            i += 1

        grants_array_end = i - 1  # Position of closing ]

        # Parse existing grants from HCL
        grants_content = content[grants_array_start:grants_array_end]
        existing_grants = self._parse_grants_from_hcl(grants_content)

        # Build merged grants dict keyed by (database, table)
        merged_grants: Dict[tuple, List[str]] = {}

        if replace_grants:
            # REPLACE MODE: Replace grants only for databases in new_grants
            # Keep existing grants for databases NOT being updated
            databases_being_updated = {grant['database'] for grant in new_grants}

            # Keep existing grants for databases not in the update
            for grant in existing_grants:
                if grant['database'] not in databases_being_updated:
                    key = (grant['database'], grant['table'])
                    merged_grants[key] = list(grant['privileges'])

            # Add/replace grants for databases being updated
            for grant in new_grants:
                key = (grant['database'], grant['table'])
                merged_grants[key] = sorted(grant['privileges'])
        else:
            # MERGE MODE: Union privileges with existing grants
            # Add existing grants to merged dict
            for grant in existing_grants:
                key = (grant['database'], grant['table'])
                merged_grants[key] = list(grant['privileges'])

            # Merge new grants - union privileges for same (database, table)
            for grant in new_grants:
                key = (grant['database'], grant['table'])
                if key in merged_grants:
                    # Union privileges and sort for consistency
                    existing_privs = set(merged_grants[key])
                    new_privs = set(grant['privileges'])
                    merged_grants[key] = sorted(existing_privs | new_privs)
                else:
                    # New (database, table) combination
                    merged_grants[key] = sorted(grant['privileges'])

        # Format merged grants as HCL
        merged_grants_hcl_items = []
        for (database, table), privileges in merged_grants.items():
            grant_hcl = f'''      {{
        database   = "{database}"
        table      = "{table}"
        privileges = {json.dumps(privileges)}
      }}'''
            merged_grants_hcl_items.append(grant_hcl)

