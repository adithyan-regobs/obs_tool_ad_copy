    def _flatten_psql_grants(self, grants: List[Dict]) -> List[Dict]:
        """
        Flatten nested API grants to HCL format with object_type entries.

        Input format:
            [{
                database: str,
                permissions: [str],  # database-level permissions (can be empty [])
                schemas: [{
                    schemaName: str,
                    permissions: [str],  # schema-level permissions (can be empty [])
                    tables: [{
                        tableName: str,
                        privileges: [str]  # table-level privileges (can be empty [])
                    }]
                }]
            }]

        Output format:
            [{ database, schema, object_type, privileges }, ...]

        NOTE: All object types (database, schema, table) are ALWAYS included,
              even if privileges is an empty array [].
        """
        hcl_grants = []

        for grant in grants:
            database = grant["database"]
            db_permissions = grant.get("permissions", [])

            for schema_grant in grant.get("schemas", []):
                schema_name = schema_grant["schemaName"]
                schema_permissions = schema_grant.get("permissions", [])

                # 1. Add database-level grant (ALWAYS include, even if empty)
                hcl_grants.append({
                    "database": database,
                    "schema": schema_name,
                    "object_type": "database",
                    "privileges": db_permissions
                })

                # 2. Add schema-level grant (ALWAYS include, even if empty)
                hcl_grants.append({
                    "database": database,
                    "schema": schema_name,
                    "object_type": "schema",
                    "privileges": schema_permissions
                })

                # 3. Add table-level grant (ALWAYS include, even if empty)
                # Use first table entry's privileges (frontend sends single "all" table)
                tables = schema_grant.get("tables", [])
                table_privileges = tables[0].get("privileges", []) if tables else []
                hcl_grants.append({
                    "database": database,
                    "schema": schema_name,
                    "object_type": "table",
                    "privileges": table_privileges
                })

        return hcl_grants

    def _add_or_merge_psql_user(
        self,
        existing_content: str,
        username: str,
        password: str,
        grants: List[Dict],
        update_password: bool = False,
        replace_grants: bool = True
    ) -> str:
        """
        Add new user or merge grants into existing user in psql_users array.

        Args:
            existing_content: Current HCL file content
            username: Database username
            password: KMS encrypted password
            grants: List of grants in nested API format
            update_password: If True, update password for existing user
            replace_grants: If True (default), new grants replace existing grants entirely.
                           If False, merge/union privileges with existing grants.

        Returns:
            Modified HCL content
        """
        # Extract databases being updated from original grants BEFORE flattening
        # This ensures we track databases even when all permissions are revoked
        databases_to_update = {grant['database'] for grant in grants}

        # Flatten nested grants to HCL format with object_type
        hcl_grants = self._flatten_psql_grants(grants)

        if self._check_psql_user_exists(existing_content, username):
            # User exists → merge or replace grants based on replace_grants flag
            if replace_grants:
                logger.info(f"PostgreSQL user '{username}' exists - replacing grants")
                print(f"\n⚠️  PostgreSQL user '{username}' already exists - replacing grants\n")
            else:
                logger.info(f"PostgreSQL user '{username}' exists - merging grants")
                print(f"\n⚠️  PostgreSQL user '{username}' already exists - merging grants\n")
            return self._merge_psql_user_grants(
                existing_content, username, hcl_grants,
                password=password, update_password=update_password,
                replace_grants=replace_grants,
                databases_to_update=databases_to_update
            )
        else:
            # User doesn't exist → add new user
            logger.info(f"PostgreSQL user '{username}' does not exist - adding new user")
            print(f"\n✅ Adding new PostgreSQL user '{username}'\n")
            return self._add_psql_user(existing_content, username, password, hcl_grants)

    def _add_psql_user(
        self,
        content: str,
        username: str,
        password: str,
        grants: List[Dict]
    ) -> str:
        """
        Add new user entry to psql_users array.

        Args:
            content: Full HCL file content
            username: Database username
            password: KMS encrypted password
            grants: List of flattened grants [{database, schema, object_type, privileges}]

        Returns:
            Modified HCL content with new user added
        """
        user_hcl = self._format_psql_user_hcl(username, password, grants)

        # Find psql_users = [ and its closing ]
        pattern = r'(psql_users\s*=\s*\[)'
        match = re.search(pattern, content)
        if not match:
            raise ValueError("psql_users array not found in content")

        # Find the closing bracket of psql_users array
        array_start = match.end()
        bracket_depth = 1
        i = array_start
        in_string = False
        escape_next = False

        while i < len(content) and bracket_depth > 0:
            char = content[i]

            # Handle escape sequences
            if escape_next:
                escape_next = False
                i += 1
                continue

            if char == '\\':
                escape_next = True
                i += 1
                continue

            # Handle string literals
            if char == '"' and not in_string:
                in_string = True
                i += 1
                continue

            if char == '"' and in_string:
                in_string = False
                i += 1
                continue

            # Only count brackets outside of strings
            if not in_string:
                if char == '[':
                    bracket_depth += 1
                elif char == ']':
                    bracket_depth -= 1

            i += 1

        array_end = i - 1  # Position of closing ]

        # Check if array is empty or has content
        array_content = content[array_start:array_end].strip()
        if array_content:
            # Has existing users - strip trailing whitespace before ]
            content_before_bracket = content[:array_end].rstrip()
            # Check if already ends with comma to avoid double comma
            if content_before_bracket.endswith(','):
                insert_text = f"\n{user_hcl}\n  "
            else:
                insert_text = f",\n{user_hcl}\n  "
            return content_before_bracket + insert_text + content[array_end:]
        else:
            # Empty array - just add user
            insert_text = f"\n{user_hcl}\n  "
            return content[:array_end] + insert_text + content[array_end:]

    def _merge_psql_user_grants(
        self,
        content: str,
        username: str,
        new_grants: List[Dict],
        password: str = None,
        update_password: bool = False,
        replace_grants: bool = True,
        databases_to_update: set = None
    ) -> str:
        """
        Merge or replace grants in existing PostgreSQL user's grants array.

        Args:
            content: Full HCL file content
            username: Database username
            new_grants: List of flattened grants [{database, schema, object_type, privileges}]
            password: Password to set (only used if update_password=True)
            update_password: If True, also update the user's password
            replace_grants: If True (default), new grants replace existing grants entirely.
                           If False, merge/union privileges with existing grants.
            databases_to_update: Optional set of database names being updated. If provided,
                                 this is used instead of deriving from new_grants. This is
                                 important when revoking all permissions (new_grants is empty
                                 but we still need to remove existing grants for those databases).

        Returns:
            Modified HCL content with updated grants

        Logic:
            When replace_grants=True:
                - New grants completely replace existing grants
            When replace_grants=False:
                - Same (database, schema, object_type) → union privileges
                - New combination → add grant entry
        """
        # Find the user block by name
        user_pattern = f'name\\s*=\\s*"{username}"'
        user_match = re.search(user_pattern, content)
        if not user_match:
            raise ValueError(f"PostgreSQL user '{username}' not found in content")

        # Find the grants array for this user
        grants_search_start = user_match.end()
        grants_pattern = r'grants\s*=\s*\['
        grants_match = re.search(grants_pattern, content[grants_search_start:])
        if not grants_match:
            raise ValueError(f"grants array not found for PostgreSQL user '{username}'")

        grants_array_start = grants_search_start + grants_match.end()

        # Find the closing ] of grants array
        bracket_depth = 1
        i = grants_array_start
        in_string = False
        escape_next = False

        while i < len(content) and bracket_depth > 0:
            char = content[i]

            if escape_next:
                escape_next = False
                i += 1
                continue

            if char == '\\':
                escape_next = True
                i += 1
                continue

            if char == '"' and not in_string:
                in_string = True
                i += 1
                continue

            if char == '"' and in_string:
                in_string = False
                i += 1
                continue

            if not in_string:
                if char == '[':
                    bracket_depth += 1
                elif char == ']':
                    bracket_depth -= 1

            i += 1

        grants_array_end = i - 1  # Position of closing ]

        # Parse existing grants from HCL
        grants_content = content[grants_array_start:grants_array_end]
        existing_grants = self._parse_psql_grants_from_hcl(grants_content)

        # Build merged grants dict keyed by (database, schema, object_type)
        merged_grants: Dict[tuple, List[str]] = {}

        if replace_grants:
            # REPLACE MODE: Replace grants only for databases in new_grants
            # Keep existing grants for databases NOT being updated
            # Use provided databases_to_update if available (important for revoking all permissions)
            if databases_to_update is not None:
                databases_being_updated = databases_to_update
            else:
                databases_being_updated = {grant['database'] for grant in new_grants}

            # Keep existing grants for databases not in the update
            for grant in existing_grants:
                if grant['database'] not in databases_being_updated:
                    key = (grant['database'], grant['schema'], grant['object_type'])
                    merged_grants[key] = list(grant['privileges'])

            # Add/replace grants for databases being updated
            for grant in new_grants:
                key = (grant['database'], grant['schema'], grant['object_type'])
                merged_grants[key] = sorted(grant['privileges'])
        else:
            # MERGE MODE: Union privileges with existing grants
            # Add existing grants to merged dict
            for grant in existing_grants:
                key = (grant['database'], grant['schema'], grant['object_type'])
                merged_grants[key] = list(grant['privileges'])

            # Merge new grants - union privileges for same (database, schema, object_type)
            for grant in new_grants:
                key = (grant['database'], grant['schema'], grant['object_type'])
                if key in merged_grants:
                    # Union privileges and sort for consistency
                    existing_privs = set(merged_grants[key])
                    new_privs = set(grant['privileges'])
                    merged_grants[key] = sorted(existing_privs | new_privs)
                else:
                    # New combination
                    merged_grants[key] = sorted(grant['privileges'])

        # Format merged grants as HCL
        merged_grants_hcl_items = []
        for (database, schema, object_type), privileges in merged_grants.items():
            grant_hcl = f'''        {{
          database    = "{database}"
          schema      = "{schema}"
          object_type = "{object_type}"
          privileges  = {json.dumps(privileges)}
        }}'''
            merged_grants_hcl_items.append(grant_hcl)

        merged_grants_hcl = ",\n".join(merged_grants_hcl_items)

        # Replace entire grants array content
        replacement = f"\n{merged_grants_hcl}\n      "

        modified_content = content[:grants_array_start] + replacement + content[grants_array_end:]

        # Update password if requested
        if update_password and password:
            logger.info(f"Updating password for PostgreSQL user '{username}'")
            # Find and replace password value in the user block
            password_pattern = f'(name\\s*=\\s*"{username}"[^}}]*password\\s*=\\s*")[^"]*(")'
            modified_content = re.sub(
                password_pattern,
                f'\\g<1>{password}\\g<2>',
                modified_content
            )

        return modified_content

